#!/usr/bin/env python3

# 01.06.96 — согласование падежей и числа (перенос из VBA)

def Соглпад(n: int, колич: tuple[str, str, str]) -> str:
    """
    Согласует наименование в числе и падеже с исходным значением n.

    Параметры:
        n     — количество
        колич — кортеж из 3 полных форм: (Колич0, Колич1, Колич2)
                Колич0 — для 0 и «много» (5, 6, ..., 11, 12, ...)
                Колич1 — для 1 (и 21, 31, ...)
                Колич2 — для 2–4 (и 22–24, 32–34, ...)

    Примеры:
        Соглпад(0, ("записей", "запись", "записи"))   → "записей"
        Соглпад(1, ("записей", "запись", "записи"))   → "запись"
        Соглпад(2, ("записей", "запись", "записи"))   → "записи"
        Соглпад(5, ("записей", "запись", "записи"))   → "записей"
        Соглпад(21, ("записей", "запись", "записи"))  → "запись"
        Соглпад(22, ("записей", "запись", "записи"))  → "записи"
    """
    n = n % 100
    if n > 20:
        n = n % 10
    if n == 1:
        return колич[1]
    elif 2 <= n <= 4:
        return колич[2]
    else:
        return колич[0]


if __name__ == "__main__":
    ЗАПИСЬ = ("записей", "запись", "записи")
    assert Соглпад(0, ЗАПИСЬ) == "записей"
    assert Соглпад(1, ЗАПИСЬ) == "запись"
    assert Соглпад(2, ЗАПИСЬ) == "записи"
    assert Соглпад(3, ЗАПИСЬ) == "записи"
    assert Соглпад(4, ЗАПИСЬ) == "записи"
    assert Соглпад(5, ЗАПИСЬ) == "записей"
    assert Соглпад(11, ЗАПИСЬ) == "записей"
    assert Соглпад(13, ЗАПИСЬ) == "записей"
    assert Соглпад(21, ЗАПИСЬ) == "запись"
    assert Соглпад(22, ЗАПИСЬ) == "записи"
    assert Соглпад(25, ЗАПИСЬ) == "записей"
    print("Все проверки Соглпад пройдены.")   
